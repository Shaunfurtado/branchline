function edge(fromId: string, toId: string, kind: GraphEdge['kind'], weight = 1): GraphEdge {
  return { id: `edge_${fromId}_${toId}`, fromId, toId, kind, weight };
}

const edges: GraphEdge[] = [];
for (const supplier of suppliers) {
  for (const offer of supplier.offers) edges.push(edge(supplier.id, offer.componentId, 'supplies'));
}
for (const lane of lanes) edges.push(edge(lane.fromId, lane.toId, 'ships'));
for (const factory of factories) {
  for (const productId of factory.compatibleProductIds) edges.push(edge(factory.id, productId, 'builds'));
}
for (const product of products) {
  for (const item of product.bom) edges.push(edge(item.componentId, product.id, 'depends_on', item.unitsPerVehicle));
}
for (const order of orders) {
  edges.push(edge(order.productId, order.id, 'fulfills', order.quantity));
  edges.push(edge(order.id, order.customerId, 'serves'));
  edges.push(edge(order.factoryId, order.id, 'fulfills'));
}

